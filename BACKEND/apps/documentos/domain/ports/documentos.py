"""Puertos del módulo de documentos (F-1). La infraestructura los implementa; los casos de uso solo los usan."""
from typing import Protocol

from apps.documentos.domain.entities.documentos import (
    DocumentoGenerado,
    FirmaDocumento,
    Plantilla,
    ValoresDocumento,
    VersionPlantilla,
)


class RepoPlantillas(Protocol):
    def listar(self, proceso: str | None = None, grupo: str | None = None) -> list[Plantilla]: ...
    def obtener(self, plantilla_id: str) -> Plantilla | None: ...
    def obtener_activa_por_proceso(self, proceso: str) -> Plantilla | None: ...
    def obtener_por_codigo(self, codigo: str) -> Plantilla | None: ...
    def crear(self, datos: dict) -> Plantilla: ...
    def actualizar_borrador(self, plantilla_id: str, datos: dict) -> Plantilla: ...
    def publicar(self, plantilla_id: str, actor_id: int | None) -> VersionPlantilla: ...
    def fijar_activa(self, plantilla_id: str, activa: bool) -> Plantilla: ...
    def versiones(self, plantilla_id: str) -> list[VersionPlantilla]: ...
    def obtener_version(self, plantilla_id: str, numero: int) -> VersionPlantilla | None: ...
    def ultima_version(self, plantilla_id: str) -> VersionPlantilla | None: ...


class RepoDocumentos(Protocol):
    def guardar_generado(self, datos: dict) -> DocumentoGenerado: ...
    def obtener_generado(self, documento_id: str) -> DocumentoGenerado | None: ...
    def listar_generados(self, sujeto_tipo: str, sujeto_id: str) -> list[DocumentoGenerado]: ...
    def guardar_firma(self, datos: dict) -> FirmaDocumento: ...
    def firmas_de(self, documento_id: str) -> list[FirmaDocumento]: ...
    def vincular_trabajador(self, sujeto_tipo: str, sujeto_id: str, cedula: str) -> int: ...
    def documentos_de_trabajador(self, cedula: str) -> list[DocumentoGenerado]: ...
    def guardar_valores(self, sujeto_tipo: str, sujeto_id: str, plantilla_id: str, valores: dict) -> ValoresDocumento: ...
    def valores_de(self, sujeto_tipo: str, sujeto_id: str) -> dict[str, dict]: ...


class ProveedorDatosDocumento(Protocol):
    """Entrega los datos conocidos del sujeto (postulante/trabajador) con las claves del catálogo de variables.

    La implementación real vive en `postulacion.infrastructure` (el expediente); las pruebas de la plantilla usan uno falso.
    Con `con_foto=False` no se descarga la imagen (listados): el dict trae igual `_foto_sha256` (huella de la foto).
    """

    def datos_de(self, sujeto_tipo: str, sujeto_id: str, con_foto: bool = True) -> dict: ...


class AlmacenArchivos(Protocol):
    def subir(self, clave: str, contenido: bytes, mime_type: str = 'application/octet-stream') -> str: ...
    def descargar(self, clave: str) -> bytes: ...


class MotorPdf(Protocol):
    def renderizar(self, version_o_borrador: dict, datos: dict) -> bytes:
        """`version_o_borrador`: {modo, definicion, campos_propios, fondo_clave, fondo_paginas, ...}."""

    def renderizar_pagina_fondo(self, contenido_pdf: bytes, numero: int) -> bytes: ...


class InspectorPdf(Protocol):
    def inspeccionar(self, contenido: bytes) -> list[dict]:
        """[{numero, ancho_mm, alto_mm}] por página; lanza ValidationError si el PDF no es utilizable."""
